//! observe generates an observed-state fixture for tests/render: it renders
//! a case until nothing new appears, then reports every composed object as
//! existing and healthy (provider-kubernetes Objects through
//! status.atProvider.manifest).
//!
//!     observe <api> <case>   # writes tests/render/<api>/observed/<case>.yaml
//!
//! Needs the crossplane CLI and a Docker API, like tests/render/run.sh, and
//! function-basis built from this checkout (run.sh builds it; or
//! docker build -f function/Dockerfile -t localhost/function-basis:render .;
//! FUNCTION_IMAGE names another image). Health is what the compositions
//! look for: Namespace Active, Prometheus Available, Grafana
//! complete/success, Ready=True conditions (CNPG Cluster, Objects), a
//! provisioned BucketClaim and a granted BucketAccess (COSI), a CronJob
//! whose last run succeeded.

use basis_tools::doc::{self, root};
use basis_tools::{at, s, yaml};
use serde_json::{Map, Value, json};
use std::path::Path;
use std::process::Command;

const RESOURCE_NAME: &str = "crossplane.io/composition-resource-name";

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [api, kase] = args.as_slice() else {
        eprintln!("usage: observe <api> <case>");
        std::process::exit(2);
    };
    if let Err(e) = run(api, kase) {
        eprintln!("{e}");
        std::process::exit(1);
    }
}

fn run(api: &str, kase: &str) -> Result<(), String> {
    let base = root();
    let tests = base.join("tests").join("render").join(api);
    let xr_path = tests.join("xr").join(format!("{kase}.yaml"));
    let mut required = tests.join("required").join(format!("{kase}.yaml"));
    if !required.exists() {
        required = tests.join("required").join("default.yaml");
    }
    let xr = doc::load(&xr_path.to_string_lossy())?;
    let xr_kind = s!(&xr, "kind").to_string();

    let tmp = std::env::temp_dir().join(format!("observe-{}", std::process::id()));
    std::fs::create_dir_all(&tmp).map_err(|e| e.to_string())?;
    let result = render_until_stable(&base, api, &xr_path, &required, &xr_kind, &tmp);
    let _ = std::fs::remove_dir_all(&tmp);
    let observed = result?;

    let target = tests.join("observed").join(format!("{kase}.yaml"));
    let head = format!("# Observed state for xr/{kase}.yaml: every composed object exists and is healthy.\n\
        # Generated by hack/observe {api} {kase}; regenerate instead of editing.\n");
    std::fs::write(&target, head + &yaml::encode_all(&observed)).map_err(|e| format!("{}: {e}", target.display()))?;
    let rel = target.strip_prefix(&base).unwrap_or(&target).display().to_string();
    println!("wrote {rel} ({} resources)", observed.len());
    Ok(())
}

fn render_until_stable(base: &Path, api: &str, xr_path: &Path, required: &Path, xr_kind: &str, tmp: &Path) -> Result<Vec<Value>, String> {
    let obs_path = tmp.join("observed.yaml");
    // function-basis built from this checkout, as tests/render/run.sh builds it.
    let image = std::env::var("FUNCTION_IMAGE").ok().filter(|i| !i.is_empty()).unwrap_or_else(|| "localhost/function-basis:render".into());
    let functions = tmp.join("functions.yaml");
    std::fs::write(&functions, format!("apiVersion: pkg.crossplane.io/v1
kind: Function
metadata:
  name: function-basis
  annotations:
    render.crossplane.io/runtime-docker-pull-policy: Never
spec:
  package: {image}\n")).map_err(|e| e.to_string())?;

    let mut observed: Vec<Value> = vec![];
    let mut seen: Vec<String> = vec![];
    for _ in 0..5 {
        let mut cmd = Command::new("crossplane");
        cmd.arg("render").arg(xr_path).arg(base.join("apis").join(api).join("composition.yaml")).arg(&functions)
            .arg("--xrd").arg(base.join("apis").join(api).join("definition.yaml"));
        if required.exists() {
            cmd.arg(format!("--required-resources={}", required.display()));
        }
        if !observed.is_empty() {
            std::fs::write(&obs_path, yaml::encode_all(&observed)).map_err(|e| e.to_string())?;
            cmd.arg(format!("--observed-resources={}", obs_path.display()));
        }
        let out = cmd.output().map_err(|e| format!("crossplane render: {e}"))?;
        if !out.status.success() {
            return Err(format!("crossplane render: {}\n{}", out.status, String::from_utf8_lossy(&out.stderr)));
        }
        let docs = doc::decode_all(&String::from_utf8_lossy(&out.stdout))?;
        let desired: Vec<&Value> = docs.iter().filter(|d| s!(d, "kind") != xr_kind && s!(d, "kind") != "Result").collect();
        let mut keys: Vec<String> = desired.iter().map(|d| s!(d, "metadata", "annotations", RESOURCE_NAME).to_string()).collect();
        keys.sort();
        observed = observe(&desired);
        if keys == seen {
            break;
        }
        seen = keys;
    }
    Ok(observed)
}

fn observe(desired: &[&Value]) -> Vec<Value> {
    desired.iter().map(|d| {
        let mut m: Map<String, Value> = d["metadata"].as_object().into_iter().flatten()
            .filter(|(k, _)| !matches!(k.as_str(), "labels" | "ownerReferences" | "generateName"))
            .map(|(k, v)| (k.clone(), v.clone())).collect();
        m.insert("annotations".into(), json!({RESOURCE_NAME: s!(d, "metadata", "annotations", RESOURCE_NAME)}));
        if s!(d, "kind") == "Object" {
            let manifest = at!(d, "spec", "forProvider", "manifest").filter(|m| m.is_object()).cloned().unwrap_or(Value::Null);
            json!({"apiVersion": d["apiVersion"], "kind": d["kind"], "metadata": m,
                "status": {
                    "atProvider": {"manifest": healthy(&manifest)},
                    "conditions": [
                        {"type": "Ready", "status": "True", "reason": "Available"},
                        {"type": "Synced", "status": "True", "reason": "ReconcileSuccess"},
                    ],
                }})
        } else {
            let mut o = (*d).clone();
            o["metadata"] = Value::Object(m);
            let mut o = healthy(&o);
            if let Some(map) = o.as_object_mut() {
                map.remove("spec");
            }
            o
        }
    }).collect()
}

fn healthy(obj: &Value) -> Value {
    let mut obj = match obj {
        Value::Object(_) => obj.clone(),
        // A missing manifest stays as Go's nil map reads: null.
        _ => return Value::Null,
    };
    let ready = json!([{"type": "Ready", "status": "True", "reason": "Available"}]);
    let status = match s!(&obj, "kind") {
        "Namespace" => json!({"phase": "Active"}),
        "Prometheus" => json!({"conditions": [{"type": "Available", "status": "True"}]}),
        "Grafana" => json!({"stage": "complete", "stageStatus": "success"}),
        "Cluster" => {
            let n = at!(&obj, "spec", "instances").cloned().unwrap_or(Value::Null);
            json!({"phase": "Cluster in healthy state", "instances": n, "readyInstances": n,
                "currentPrimary": format!("{}-1", s!(&obj, "metadata", "name")), "conditions": ready})
        }
        "Database" => json!({"applied": true}),
        "BucketClaim" => json!({"bucketName": format!("{}-{}-0f3a", s!(&obj, "metadata", "namespace"), s!(&obj, "metadata", "name")), "bucketReady": true}),
        "BucketAccess" => json!({"accessGranted": true, "accountID": "e2e"}),
        "CronJob" => json!({"lastScheduleTime": "2026-01-01T00:05:00Z", "lastSuccessfulTime": "2026-01-01T00:05:04Z"}),
        _ => return obj,
    };
    obj["status"] = status;
    obj
}
