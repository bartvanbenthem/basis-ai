// Command observe generates an observed-state fixture for tests/render: it
// renders a case until nothing new appears, then reports every composed
// object as existing and healthy (provider-kubernetes Objects through
// status.atProvider.manifest).
//
//	go run ./hack/observe <api> <case>   # writes tests/render/<api>/observed/<case>.yaml
//
// Needs the crossplane CLI and a Docker API, like tests/render/run.sh. Health
// is what the compositions look for: Namespace Active, Prometheus Available,
// Grafana complete/success, Ready=True conditions (CNPG Cluster, Objects), a
// provisioned BucketClaim and a granted BucketAccess (COSI), a CronJob whose
// last run succeeded.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"slices"
	"sort"

	"gopkg.in/yaml.v3"

	"github.com/bartvanbenthem/basis-ai/api/internal/doc"
)

type M = doc.M

const resourceName = "crossplane.io/composition-resource-name"

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: observe <api> <case>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func root() string {
	_, file, _, _ := runtime.Caller(0)
	return filepath.Dir(filepath.Dir(filepath.Dir(file)))
}

func exists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

func run(api, kase string) error {
	base := root()
	tests := filepath.Join(base, "tests", "render", api)
	xrPath := filepath.Join(tests, "xr", kase+".yaml")
	required := filepath.Join(tests, "required", kase+".yaml")
	if !exists(required) {
		required = filepath.Join(tests, "required", "default.yaml")
	}
	xr, err := doc.Load(xrPath)
	if err != nil {
		return err
	}
	xrKind := doc.Str(xr, "kind")

	tmp, err := os.MkdirTemp("", "observe-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	obsPath := filepath.Join(tmp, "observed.yaml")

	var observed []M
	var seen []string
	for range 5 {
		args := []string{"render", xrPath,
			filepath.Join(base, "apis", api, "composition.yaml"),
			filepath.Join(base, "install", "functions.yaml"),
			"--xrd", filepath.Join(base, "apis", api, "definition.yaml")}
		if exists(required) {
			args = append(args, "--required-resources="+required)
		}
		if len(observed) > 0 {
			if err := writeAll(obsPath, "", observed); err != nil {
				return err
			}
			args = append(args, "--observed-resources="+obsPath)
		}
		cmd := exec.Command("crossplane", args...)
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		out, err := cmd.Output()
		if err != nil {
			return fmt.Errorf("crossplane render: %w\n%s", err, stderr.String())
		}
		docs, err := doc.DecodeAll(out)
		if err != nil {
			return err
		}
		var desired []M
		var keys []string
		for _, d := range docs {
			if k := doc.Str(d, "kind"); k == xrKind || k == "Result" {
				continue
			}
			desired = append(desired, d)
			keys = append(keys, doc.Str(d, "metadata", "annotations", resourceName))
		}
		sort.Strings(keys)
		observed = observe(desired)
		if slices.Equal(keys, seen) {
			break
		}
		seen = keys
	}

	target := filepath.Join(tests, "observed", kase+".yaml")
	head := fmt.Sprintf("# Observed state for xr/%s.yaml: every composed object exists and is healthy.\n"+
		"# Generated by hack/observe %s %s; regenerate instead of editing.\n", kase, api, kase)
	if err := writeAll(target, head, observed); err != nil {
		return err
	}
	rel, _ := filepath.Rel(base, target)
	fmt.Printf("wrote %s (%d resources)\n", rel, len(observed))
	return nil
}

func writeAll(path, head string, docs []M) error {
	var buf bytes.Buffer
	buf.WriteString(head)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	for _, d := range docs {
		if err := enc.Encode(d); err != nil {
			return err
		}
	}
	if err := enc.Close(); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}

func observe(desired []M) []M {
	var out []M
	for _, d := range desired {
		meta := doc.Map(d, "metadata")
		m := M{}
		for k, v := range meta {
			switch k {
			case "labels", "ownerReferences", "generateName":
			default:
				m[k] = v
			}
		}
		m["annotations"] = M{resourceName: doc.Str(d, "metadata", "annotations", resourceName)}
		if doc.Str(d, "kind") == "Object" {
			d = M{"apiVersion": d["apiVersion"], "kind": d["kind"], "metadata": m,
				"status": M{
					"atProvider": M{"manifest": healthy(doc.Map(d, "spec", "forProvider", "manifest"))},
					"conditions": doc.L{
						M{"type": "Ready", "status": "True", "reason": "Available"},
						M{"type": "Synced", "status": "True", "reason": "ReconcileSuccess"},
					},
				}}
		} else {
			d = healthy(clone(d, m))
			delete(d, "spec")
		}
		out = append(out, d)
	}
	return out
}

// clone copies the top level of d with replaced metadata.
func clone(d M, meta M) M {
	c := M{}
	for k, v := range d {
		c[k] = v
	}
	c["metadata"] = meta
	return c
}

func healthy(obj M) M {
	obj = clone(obj, doc.Map(obj, "metadata"))
	ready := doc.L{M{"type": "Ready", "status": "True", "reason": "Available"}}
	switch doc.Str(obj, "kind") {
	case "Namespace":
		obj["status"] = M{"phase": "Active"}
	case "Prometheus":
		obj["status"] = M{"conditions": doc.L{M{"type": "Available", "status": "True"}}}
	case "Grafana":
		obj["status"] = M{"stage": "complete", "stageStatus": "success"}
	case "Cluster":
		n := doc.Get(obj, "spec", "instances")
		obj["status"] = M{"phase": "Cluster in healthy state", "instances": n, "readyInstances": n,
			"currentPrimary": doc.Str(obj, "metadata", "name") + "-1", "conditions": ready}
	case "Database":
		obj["status"] = M{"applied": true}
	case "BucketClaim":
		obj["status"] = M{"bucketName": fmt.Sprintf("%s-%s-0f3a", doc.Str(obj, "metadata", "namespace"),
			doc.Str(obj, "metadata", "name")), "bucketReady": true}
	case "BucketAccess":
		obj["status"] = M{"accessGranted": true, "accountID": "e2e"}
	case "CronJob":
		obj["status"] = M{"lastScheduleTime": "2026-01-01T00:05:00Z", "lastSuccessfulTime": "2026-01-01T00:05:04Z"}
	}
	return obj
}
