// Command generate prepares the vendored sources the composition function
// embeds, for PostgresCluster (function/postgrescluster/assets):
//
//	src/dashboards/cnpg-cluster.json    -> zz_generated.dashboard.json
//	src/alerts/cnpg-cluster-rules.yaml  -> zz_generated.alert-rules.yaml
//
// and for ValkeyCache (function/valkeycache/assets):
//
//	src/dashboards/valkey-cache.json    -> zz_generated.dashboard.json
//	src/alerts/valkey-cache-rules.yaml  -> zz_generated.alert-rules.yaml
//
// and the OpenAPI documents of the APIs for the portal (see openapi.go).
//
// src/alerts/local-rules.yaml holds our changes to the upstream alerts (a rule
// there replaces the upstream rule of the same name), so that
// hack/refresh-alerts.sh can overwrite cnpg-cluster-rules.yaml freely.
//
// They keep placeholders (zzclusterzz, zznamespacezz, zzuidzz) that the
// function replaces, so each PostgresCluster and ValkeyCache gets its own
// dashboard title/uid/preselected variables and scoped alert rules.
//
//	go run ./hack/generate          # write the assets
//	go run ./hack/generate --check  # exit 1 if an asset is stale
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
	"unicode/utf16"

	"gopkg.in/yaml.v3"
)

// Placeholders the function substitutes (function/*/assets.go).
const (
	cluster   = "zzclusterzz"
	namespace = "zznamespacezz"
	uid       = "zzuidzz"
)

const header = "# GENERATED by hack/generate from src/alerts -- DO NOT EDIT.\n"

func main() {
	check := flag.Bool("check", false, "exit 1 if an asset is stale")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func root() string {
	// hack/generate/main.go -> the api directory, whatever the cwd.
	_, file, _, _ := runtime.Caller(0)
	return filepath.Dir(filepath.Dir(filepath.Dir(file)))
}

func run(check bool) error {
	base := root()
	alerts := filepath.Join(base, "src", "alerts")
	var outputs []struct{ path, content string }
	for _, a := range []struct {
		pkg, dashboard, titlePrefix string
		rules                       []string // upstream, then optional local overrides
	}{
		{"postgrescluster", "cnpg-cluster.json", "CloudNativePG", []string{"cnpg-cluster-rules.yaml", "local-rules.yaml"}},
		{"valkeycache", "valkey-cache.json", "Valkey", []string{"valkey-cache-rules.yaml"}},
	} {
		assets := filepath.Join(base, "function", a.pkg, "assets")
		dash, err := dashboard(filepath.Join(base, "src", "dashboards", a.dashboard), a.titlePrefix)
		if err != nil {
			return err
		}
		local := ""
		if len(a.rules) > 1 {
			local = filepath.Join(alerts, a.rules[1])
		}
		rules, err := alertRules(filepath.Join(alerts, a.rules[0]), local)
		if err != nil {
			return err
		}
		outputs = append(outputs,
			struct{ path, content string }{filepath.Join(assets, "zz_generated.dashboard.json"), dash + "\n"},
			struct{ path, content string }{filepath.Join(assets, "zz_generated.alert-rules.yaml"), header + rules + "\n"})
	}
	docs, err := openAPIDocs(base)
	if err != nil {
		return err
	}
	outputs = append(outputs, docs...)
	for _, o := range outputs {
		rel, _ := filepath.Rel(base, o.path)
		if check {
			current, err := os.ReadFile(o.path)
			if err != nil || string(current) != o.content {
				return fmt.Errorf("%s is stale: run `make generate`", rel)
			}
			fmt.Printf("%s is up to date\n", rel)
			continue
		}
		if err := os.WriteFile(o.path, []byte(o.content), 0o644); err != nil {
			return err
		}
		fmt.Printf("wrote %s (%d KiB)\n", rel, len(o.content)/1024)
	}
	return nil
}

// splitLines splits like Python's str.splitlines for \n-terminated text.
func splitLines(s string) []string {
	s = strings.TrimSuffix(s, "\n")
	if s == "" {
		return nil
	}
	return strings.Split(s, "\n")
}

func dashboard(path, titlePrefix string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	d, err := parseJSON(raw)
	if err != nil {
		return "", fmt.Errorf("%s: %w", path, err)
	}
	dash, ok := d.(*object)
	if !ok {
		return "", fmt.Errorf("%s: not a JSON object", path)
	}
	dash.set("title", titlePrefix+" / "+namespace+" / "+cluster)
	dash.set("uid", uid)
	templating, _ := dash.get("templating").(*object)
	if templating != nil {
		list, _ := templating.get("list").([]any)
		for _, v := range list {
			variable, ok := v.(*object)
			if !ok {
				continue
			}
			var current string
			switch variable.get("name") {
			case "namespace":
				current = namespace
			case "cluster":
				current = cluster
			default:
				continue
			}
			sel := &object{}
			sel.set("selected", true)
			sel.set("text", current)
			sel.set("value", current)
			variable.set("current", sel)
		}
	}
	// Compact: the GrafanaDashboard carries it; the readable source stays
	// in src/dashboards/.
	var buf strings.Builder
	writeJSON(&buf, dash)
	return buf.String(), nil
}

// alertRules emits the merged rules as one YAML sequence. A rule in local
// replaces the upstream rule of the same name in place; one with a new name
// is appended (no local file: none). Both files are top-level block
// sequences, so each item is embedded exactly as formatted there.
func alertRules(upstream, local string) (string, error) {
	rules, err := readRules(upstream)
	if err != nil {
		return "", err
	}
	var overrides []alertRule
	if local != "" {
		if overrides, err = readRules(local); err != nil {
			return "", err
		}
	}
	for _, o := range overrides {
		replaced := false
		for i := range rules {
			if rules[i].alert == o.alert {
				rules[i], replaced = o, true
				break
			}
		}
		if !replaced {
			rules = append(rules, o)
		}
	}
	var out []string
	for _, r := range rules {
		out = append(out, r.body)
	}
	return strings.Join(out, "\n"), nil
}

type alertRule struct{ alert, body string }

// readRules splits a rules file into its list items, keeping each item's text.
func readRules(path string) ([]alertRule, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var items [][]string
	for _, line := range splitLines(string(raw)) {
		switch {
		case strings.HasPrefix(line, "- "):
			items = append(items, []string{line})
		case len(items) == 0:
			if line != "" && !strings.HasPrefix(line, "#") {
				return nil, fmt.Errorf("%s: expected a YAML sequence of rules, got %q", path, line)
			}
		default:
			items[len(items)-1] = append(items[len(items)-1], line)
		}
	}
	var rules []alertRule
	for _, item := range items {
		body := strings.TrimRight(strings.Join(item, "\n"), "\n")
		var rule []struct {
			Alert string `yaml:"alert"`
		}
		if err := yaml.Unmarshal([]byte(body), &rule); err != nil || len(rule) != 1 || rule[0].Alert == "" {
			return nil, fmt.Errorf("%s: cannot read rule %q: %v", path, item[0], err)
		}
		rules = append(rules, alertRule{rule[0].Alert, body})
	}
	return rules, nil
}

// --- order-preserving JSON, written the way Python's
// json.dumps(..., separators=(",", ":")) does (ASCII-only, floats as repr).

type member struct {
	key   string
	value any
}

type object struct{ members []member }

func (o *object) get(key string) any {
	for _, m := range o.members {
		if m.key == key {
			return m.value
		}
	}
	return nil
}

// set replaces a key in place, or appends it like a Python dict would.
func (o *object) set(key string, value any) {
	for i := range o.members {
		if o.members[i].key == key {
			o.members[i].value = value
			return
		}
	}
	o.members = append(o.members, member{key, value})
}

func parseJSON(raw []byte) (any, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	v, err := parseValue(dec)
	if err != nil {
		return nil, err
	}
	if _, err := dec.Token(); !errors.Is(err, io.EOF) {
		return nil, errors.New("trailing data after JSON value")
	}
	return v, nil
}

func parseValue(dec *json.Decoder) (any, error) {
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	switch t := tok.(type) {
	case json.Delim:
		switch t {
		case '{':
			o := &object{}
			for dec.More() {
				k, err := dec.Token()
				if err != nil {
					return nil, err
				}
				v, err := parseValue(dec)
				if err != nil {
					return nil, err
				}
				o.set(k.(string), v)
			}
			_, err := dec.Token()
			return o, err
		case '[':
			l := []any{}
			for dec.More() {
				v, err := parseValue(dec)
				if err != nil {
					return nil, err
				}
				l = append(l, v)
			}
			_, err := dec.Token()
			return l, err
		}
		return nil, fmt.Errorf("unexpected %v", t)
	}
	return tok, nil
}

func writeJSON(b *strings.Builder, v any) {
	switch x := v.(type) {
	case *object:
		b.WriteByte('{')
		for i, m := range x.members {
			if i > 0 {
				b.WriteByte(',')
			}
			writeString(b, m.key)
			b.WriteByte(':')
			writeJSON(b, m.value)
		}
		b.WriteByte('}')
	case []any:
		b.WriteByte('[')
		for i, e := range x {
			if i > 0 {
				b.WriteByte(',')
			}
			writeJSON(b, e)
		}
		b.WriteByte(']')
	case string:
		writeString(b, x)
	case json.Number:
		b.WriteString(number(x))
	case bool:
		b.WriteString(strconv.FormatBool(x))
	case nil:
		b.WriteString("null")
	default:
		panic(fmt.Sprintf("writeJSON: unexpected %T", v))
	}
}

// number keeps integers as written and prints floats like Python's repr
// (shortest round-trip digits, two-digit exponents: 1e-9 -> 1e-09).
func number(n json.Number) string {
	s := n.String()
	if !strings.ContainsAny(s, ".eE") {
		return s
	}
	f, err := n.Float64()
	if err != nil {
		return s
	}
	exp := 0
	if f != 0 {
		exp, _ = strconv.Atoi(strings.SplitN(strconv.FormatFloat(f, 'e', -1, 64), "e", 2)[1])
	}
	if f != 0 && (exp < -4 || exp >= 16) {
		return strconv.FormatFloat(f, 'e', -1, 64)
	}
	out := strconv.FormatFloat(f, 'f', -1, 64)
	if !strings.Contains(out, ".") {
		out += ".0"
	}
	return out
}

func writeString(b *strings.Builder, s string) {
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case '\b':
			b.WriteString(`\b`)
		case '\f':
			b.WriteString(`\f`)
		default:
			switch {
			case r < 0x20 || (r > 0x7f && r <= 0xffff):
				fmt.Fprintf(b, `\u%04x`, r)
			case r > 0xffff:
				hi, lo := utf16.EncodeRune(r)
				fmt.Fprintf(b, `\u%04x\u%04x`, hi, lo)
			default:
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
}
