package main

// OpenAPI documents of the platform's APIs, and the Backstage API entities
// the portal's API docs show them from:
//
//	apis/<api>/definition.yaml -> ../portal/catalog/apis/<api>.openapi.yaml
//	                           -> ../portal/catalog/apis.yaml (the documents inline:
//	                              the catalog can't resolve $text against a file location)
//
// Each XRD becomes the Kubernetes REST paths of its resource (list, create,
// get, replace, patch, delete) and the schema of the CRD Crossplane makes of
// it: the XRD's own fields plus what Crossplane adds to every composite
// resource (spec.crossplane, status.conditions; see crossplaneFields). The
// XRD's CEL rules (x-kubernetes-validations) are folded into the
// descriptions, where API docs show them.

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

// The APIs to document, in apis/, with their catalog entity's title and description.
var openAPIs = []struct{ name, title, description string }{
	{"postgrescluster", "PostgresCluster API", "A production-ready PostgreSQL cluster (postgres.cndev.nl/v1alpha1), namespaced in its Project"},
	{"project", "Project API", "A team's namespace with its locations, access, quota, Prometheus and Grafana (platform.cndev.nl/v1alpha1)"},
	{"location", "Location API", "A Kubernetes cluster the platform runs workloads in (platform.cndev.nl/v1alpha1)"},
	{"genaistack", "GenAIStack API", "A generative AI stack in a Project's site(s): RAG database, cache, model gateway and wiring (ai.cndev.nl/v1alpha1)"},
	{"modelgateway", "ModelGateway API", "An OpenAI-compatible gateway to a Project's models, hosted and self-hosted, with a key per client (ai.cndev.nl/v1alpha1)"},
	{"valkeycache", "ValkeyCache API", "An exact or semantic Valkey cache for an AI service (cache.cndev.nl/v1alpha1), namespaced in its Project"},
}

const apiEntitiesHeader = `# GENERATED by hack/generate from api/apis/*/definition.yaml -- DO NOT EDIT.
# The platform's APIs in the catalog, each with its OpenAPI document
# (also in apis/<api>.openapi.yaml), for the portal's API reference.
`

const openAPIHeader = "# GENERATED by hack/generate from api/apis/%s/definition.yaml -- DO NOT EDIT.\n"

type xrd struct {
	Spec struct {
		Group                 string `yaml:"group"`
		Scope                 string `yaml:"scope"`
		DefaultCompositionRef struct {
			Name string `yaml:"name"`
		} `yaml:"defaultCompositionRef"`
		Names struct {
			Kind       string   `yaml:"kind"`
			Plural     string   `yaml:"plural"`
			ShortNames []string `yaml:"shortNames"`
		} `yaml:"names"`
		Versions []struct {
			Name   string `yaml:"name"`
			Served bool   `yaml:"served"`
			Schema struct {
				OpenAPIV3Schema map[string]any `yaml:"openAPIV3Schema"`
			} `yaml:"schema"`
		} `yaml:"versions"`
	} `yaml:"spec"`
}

// openAPIDocs returns the OpenAPI document of every API, by output path.
func openAPIDocs(base string) ([]struct{ path, content string }, error) {
	var out []struct{ path, content string }
	entities := apiEntitiesHeader
	for _, a := range openAPIs {
		api := a.name
		raw, err := os.ReadFile(filepath.Join(base, "apis", api, "definition.yaml"))
		if err != nil {
			return nil, err
		}
		var def xrd
		if err := yaml.Unmarshal(raw, &def); err != nil {
			return nil, fmt.Errorf("apis/%s/definition.yaml: %w", api, err)
		}
		doc, err := openAPIDoc(def)
		if err != nil {
			return nil, fmt.Errorf("apis/%s/definition.yaml: %w", api, err)
		}
		var buf bytes.Buffer
		enc := yaml.NewEncoder(&buf)
		enc.SetIndent(2)
		if err := enc.Encode(doc); err != nil {
			return nil, err
		}
		out = append(out, struct{ path, content string }{
			filepath.Join(base, "..", "portal", "catalog", "apis", api+".openapi.yaml"),
			fmt.Sprintf(openAPIHeader, api) + buf.String(),
		})
		entity := map[string]any{
			"apiVersion": "backstage.io/v1alpha1",
			"kind":       "API",
			"metadata":   map[string]any{"name": api, "title": a.title, "description": a.description, "tags": []any{"kubernetes", "crossplane"}},
			"spec": map[string]any{"type": "openapi", "lifecycle": "experimental", "owner": "guests", "system": "basis",
				"definition": buf.String()},
		}
		var eb bytes.Buffer
		enc = yaml.NewEncoder(&eb)
		enc.SetIndent(2)
		if err := enc.Encode(entity); err != nil {
			return nil, err
		}
		entities += "---\n" + eb.String()
	}
	out = append(out, struct{ path, content string }{filepath.Join(base, "..", "portal", "catalog", "apis.yaml"), entities})
	return out, nil
}

func openAPIDoc(def xrd) (map[string]any, error) {
	s := def.Spec
	var version string
	var schema map[string]any
	for _, v := range s.Versions {
		if v.Served {
			version, schema = v.Name, v.Schema.OpenAPIV3Schema
			break
		}
	}
	if schema == nil {
		return nil, fmt.Errorf("no served version with a schema")
	}
	kind, plural, apiVersion := s.Names.Kind, s.Names.Plural, s.Group+"/"+version
	namespaced := s.Scope != "Cluster"

	// The object: apiVersion, kind and metadata around the XRD's spec and status.
	object := foldValidations(schema).(map[string]any)
	props, _ := object["properties"].(map[string]any)
	if props == nil {
		props = map[string]any{}
		object["properties"] = props
	}
	props["apiVersion"] = map[string]any{"type": "string", "enum": []any{apiVersion}}
	props["kind"] = map[string]any{"type": "string", "enum": []any{kind}}
	props["metadata"] = map[string]any{"$ref": "#/components/schemas/ObjectMeta"}
	object["required"] = []any{"apiVersion", "kind", "metadata"}
	crossplaneFields(props, s.DefaultCompositionRef.Name, namespaced)

	ref := map[string]any{"$ref": "#/components/schemas/" + kind}
	one := func(desc string) map[string]any {
		return map[string]any{"description": desc, "content": map[string]any{"application/json": map[string]any{"schema": ref}}}
	}
	errors := map[string]any{
		"401": map[string]any{"description": "Not authenticated"},
		"403": map[string]any{"description": "Not allowed (RBAC), or refused by an admission policy"},
		"404": map[string]any{"description": "Not found"},
		"422": map[string]any{"description": "Invalid: the schema or one of its rules rejects it"},
	}
	responses := func(codes map[string]any) map[string]any {
		for k, v := range errors {
			codes[k] = v
		}
		return codes
	}
	nameParam := map[string]any{"name": "name", "in": "path", "required": true, "schema": map[string]any{"type": "string"}, "description": kind + " name"}
	dryRun := map[string]any{"name": "dryRun", "in": "query", "schema": map[string]any{"type": "string", "enum": []any{"All"}},
		"description": "All: validate (schema, rules, admission policies) without persisting"}
	var common []any
	collection := fmt.Sprintf("/apis/%s/%s/%s", s.Group, version, plural)
	where := ""
	if namespaced {
		collection = fmt.Sprintf("/apis/%s/%s/namespaces/{namespace}/%s", s.Group, version, plural)
		common = append(common, map[string]any{"name": "namespace", "in": "path", "required": true,
			"schema": map[string]any{"type": "string"}, "description": "The Project's namespace"})
		where = " in a namespace"
	}
	tag := []any{kind}
	body := map[string]any{"required": true, "content": map[string]any{"application/json": map[string]any{"schema": ref}}}
	patchBody := map[string]any{"required": true, "content": map[string]any{
		"application/merge-patch+json": map[string]any{"schema": map[string]any{"type": "object"}},
		"application/apply-patch+yaml": map[string]any{"schema": map[string]any{"type": "object"}},
	}}
	paths := map[string]any{
		collection: map[string]any{
			"parameters": common,
			"get": map[string]any{"tags": tag, "operationId": "list" + kind, "summary": "List " + plural + where,
				"responses": responses(map[string]any{"200": map[string]any{"description": "OK", "content": map[string]any{
					"application/json": map[string]any{"schema": map[string]any{"type": "object", "properties": map[string]any{
						"items": map[string]any{"type": "array", "items": ref}}}}}}})},
			"post": map[string]any{"tags": tag, "operationId": "create" + kind, "summary": "Create a " + kind,
				"parameters": []any{dryRun}, "requestBody": body,
				"responses": responses(map[string]any{"201": one("Created"), "409": map[string]any{"description": "Already exists"}})},
		},
		collection + "/{name}": map[string]any{
			"parameters": append(append([]any{}, common...), nameParam),
			"get": map[string]any{"tags": tag, "operationId": "read" + kind, "summary": "Read a " + kind,
				"responses": responses(map[string]any{"200": one("OK")})},
			"put": map[string]any{"tags": tag, "operationId": "replace" + kind, "summary": "Replace a " + kind,
				"parameters": []any{dryRun}, "requestBody": body,
				"responses": responses(map[string]any{"200": one("OK"), "409": map[string]any{"description": "Conflict: changed since read (resourceVersion)"}})},
			"patch": map[string]any{"tags": tag, "operationId": "patch" + kind,
				"summary":     "Change fields of a " + kind,
				"description": "JSON merge patch (only the fields sent change, null removes one) or server-side apply.",
				"parameters":  []any{dryRun}, "requestBody": patchBody,
				"responses": responses(map[string]any{"200": one("OK")})},
			"delete": map[string]any{"tags": tag, "operationId": "delete" + kind, "summary": "Delete a " + kind,
				"responses": responses(map[string]any{"200": map[string]any{"description": "Deletion started"}})},
		},
	}

	desc, _ := schema["description"].(string)
	short := ""
	if len(s.Names.ShortNames) > 0 {
		short = fmt.Sprintf(" (short name `%s`)", strings.Join(s.Names.ShortNames, "`, `"))
	}
	scope := "cluster-scoped"
	if namespaced {
		scope = "namespaced: it lives in its Project's namespace"
	}
	return map[string]any{
		"openapi": "3.0.3",
		"info": map[string]any{
			"title":   fmt.Sprintf("%s (%s)", kind, apiVersion),
			"version": version,
			"description": fmt.Sprintf("%s\n\nA Crossplane composite resource on the platform's control plane, %s. "+
				"Use it with `kubectl`%s, GitOps, or the Kubernetes API below; the portal and its software "+
				"templates create it the same way. This is the CRD Crossplane makes of the XRD (api/apis): the "+
				"platform's fields plus Crossplane's own (spec.crossplane, status.conditions), so it is what the "+
				"API server validates: the schema, its defaults and the rules listed under each field.", desc, scope, short),
		},
		"servers": []any{map[string]any{"url": "https://{apiserver}", "description": "The control plane's Kubernetes API server",
			"variables": map[string]any{"apiserver": map[string]any{"default": "kubernetes.default.svc"}}}},
		"security": []any{map[string]any{"bearerAuth": []any{}}},
		"tags":     []any{map[string]any{"name": kind, "description": desc}},
		"paths":    paths,
		"components": map[string]any{
			"securitySchemes": map[string]any{"bearerAuth": map[string]any{"type": "http", "scheme": "bearer",
				"description": "A Kubernetes token (OIDC or ServiceAccount) with RBAC on " + plural + "." + s.Group}},
			"schemas": map[string]any{
				kind: object,
				"ObjectMeta": map[string]any{"type": "object", "description": "Standard Kubernetes object metadata (the fields that matter here).",
					"required": []any{"name"},
					"properties": map[string]any{
						"name":        map[string]any{"type": "string"},
						"namespace":   map[string]any{"type": "string"},
						"labels":      map[string]any{"type": "object", "additionalProperties": map[string]any{"type": "string"}},
						"annotations": map[string]any{"type": "object", "additionalProperties": map[string]any{"type": "string"}},
					}},
			},
		},
	}, nil
}

// crossplaneFields adds what Crossplane (v2) puts into the CRD of every
// composite resource next to the XRD's schema, as the CRD on the control
// plane has it: spec.crossplane, how Crossplane composes the resource, and
// status.conditions.
func crossplaneFields(props map[string]any, defaultComposition string, namespaced bool) {
	str := func(desc string) map[string]any { return map[string]any{"type": "string", "description": desc} }
	labels := map[string]any{"type": "object", "required": []any{"matchLabels"}, "properties": map[string]any{
		"matchLabels": map[string]any{"type": "object", "additionalProperties": map[string]any{"type": "string"}}}}
	named := func(desc string) map[string]any {
		return map[string]any{"type": "object", "description": desc, "required": []any{"name"},
			"properties": map[string]any{"name": map[string]any{"type": "string"}}}
	}
	crossplane := map[string]any{
		"type": "object",
		"description": "Set by Crossplane: how it composes this resource. Leave it out; the platform's " +
			"composition (" + defaultComposition + ") is the only one, and Crossplane fills in the rest.",
		"properties": map[string]any{
			"compositionRef":              named("The Composition that composes this resource (default: " + defaultComposition + ")."),
			"compositionSelector":         withDesc(labels, "Selects a Composition by labels instead of compositionRef."),
			"compositionRevisionRef":      named("The Composition revision in use; Crossplane sets it."),
			"compositionRevisionSelector": withDesc(labels, "Selects the Composition revision by labels (with compositionUpdatePolicy Manual)."),
			"compositionUpdatePolicy": map[string]any{"type": "string", "enum": []any{"Automatic", "Manual"}, "default": "Automatic",
				"description": "Automatic: move to a new Composition revision as soon as there is one. Manual: stay on compositionRevisionRef."},
			"resourceRefs": map[string]any{"type": "array", "description": "The resources Crossplane composed for this one (read-only).",
				"items": map[string]any{"type": "object", "required": []any{"apiVersion", "kind"}, "properties": map[string]any{
					"apiVersion": str(""), "kind": str(""), "name": str("")}}},
		},
	}
	if !namespaced {
		// A cluster-scoped resource composes namespaced ones too.
		refs := dig(crossplane, "properties", "resourceRefs", "items", "properties")
		refs["namespace"] = str("")
	}
	if spec, ok := props["spec"].(map[string]any); ok {
		sp, _ := spec["properties"].(map[string]any)
		if sp == nil {
			sp = map[string]any{}
			spec["properties"] = sp
		}
		sp["crossplane"] = crossplane
	}
	conditions := map[string]any{
		"type": "array",
		"description": "Conditions of the resource, one per type. Crossplane sets Ready (every composed resource " +
			"is ready) and Synced (the last reconcile succeeded); the composition adds its own, e.g. PostgresReady.",
		"items": map[string]any{"type": "object", "required": []any{"type", "status", "reason", "lastTransitionTime"},
			"properties": map[string]any{
				"type":               str("e.g. Ready, Synced"),
				"status":             map[string]any{"type": "string", "enum": []any{"True", "False", "Unknown"}},
				"reason":             str("Machine-readable reason, e.g. Available, ReconcileSuccess"),
				"message":            str("Human-readable detail"),
				"lastTransitionTime": map[string]any{"type": "string", "format": "date-time"},
				"observedGeneration": map[string]any{"type": "integer", "format": "int64"},
			}},
	}
	status, ok := props["status"].(map[string]any)
	if !ok {
		status = map[string]any{"type": "object"}
		props["status"] = status
	}
	stp, _ := status["properties"].(map[string]any)
	if stp == nil {
		stp = map[string]any{}
		status["properties"] = stp
	}
	stp["conditions"] = conditions
}

// dig returns the map at path (they all exist: built above).
func dig(m map[string]any, path ...string) map[string]any {
	for _, p := range path {
		m = m[p].(map[string]any)
	}
	return m
}

func withDesc(schema map[string]any, desc string) map[string]any {
	out := map[string]any{"description": desc}
	for k, v := range schema {
		out[k] = v
	}
	return out
}

// foldValidations copies a schema, turning x-kubernetes-validations (CEL
// rules) into a "Rules:" list in the description, which API docs render;
// other x-kubernetes-* extensions go.
func foldValidations(v any) any {
	switch x := v.(type) {
	case map[string]any:
		out := map[string]any{}
		for k, val := range x {
			if strings.HasPrefix(k, "x-kubernetes-") && k != "x-kubernetes-preserve-unknown-fields" {
				continue
			}
			out[k] = foldValidations(val)
		}
		if p, ok := x["x-kubernetes-preserve-unknown-fields"].(bool); ok && p {
			delete(out, "x-kubernetes-preserve-unknown-fields")
			out["additionalProperties"] = true
		}
		rules, _ := x["x-kubernetes-validations"].([]any)
		var lines []string
		for _, r := range rules {
			m, _ := r.(map[string]any)
			msg, _ := m["message"].(string)
			if msg == "" {
				msg, _ = m["rule"].(string)
			}
			if msg != "" {
				lines = append(lines, "- "+msg)
			}
		}
		if len(lines) > 0 {
			desc, _ := out["description"].(string)
			out["description"] = strings.TrimSpace(desc + "\n\nRules:\n" + strings.Join(lines, "\n"))
		}
		return out
	case []any:
		out := make([]any, len(x))
		for i, e := range x {
			out[i] = foldValidations(e)
		}
		return out
	}
	return v
}
