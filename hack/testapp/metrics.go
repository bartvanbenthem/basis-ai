package main

import (
	"fmt"
	"io"
	"sort"
	"sync"
	"time"
)

// Metrics in the Prometheus text format, for the Project's Prometheus
// (deploy/testapp.yaml has the PodMonitor). Few enough to keep by hand.
type Metrics struct {
	mu       sync.Mutex
	requests map[[2]string]float64          // by kind and cache result
	errors   map[string]float64             // by stage
	seconds  map[string]*[2]float64         // by stage: sum, count
	buckets  map[string]map[float64]float64 // by stage
	tokens   map[string]float64             // prompt, completion
}

var latencyBuckets = []float64{0.01, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10, 30, 60}

func NewMetrics() *Metrics {
	return &Metrics{requests: map[[2]string]float64{}, errors: map[string]float64{}, seconds: map[string]*[2]float64{},
		buckets: map[string]map[float64]float64{}, tokens: map[string]float64{}}
}

func (m *Metrics) Request(kind, cache string) {
	m.mu.Lock()
	m.requests[[2]string{kind, cache}]++
	m.mu.Unlock()
}
func (m *Metrics) Error(stage string) { m.mu.Lock(); m.errors[stage]++; m.mu.Unlock() }

func (m *Metrics) Tokens(u Usage) {
	m.mu.Lock()
	defer m.mu.Unlock()
	m.tokens["prompt"] += float64(u.Prompt)
	m.tokens["completion"] += float64(u.Completion)
}

func (m *Metrics) Observe(stage string, d time.Duration) {
	m.mu.Lock()
	defer m.mu.Unlock()
	s := m.seconds[stage]
	if s == nil {
		s = &[2]float64{}
		m.seconds[stage] = s
		m.buckets[stage] = map[float64]float64{}
	}
	s[0] += d.Seconds()
	s[1]++
	for _, b := range latencyBuckets {
		if d.Seconds() <= b {
			m.buckets[stage][b]++
		}
	}
}

func (m *Metrics) Write(w io.Writer) {
	m.mu.Lock()
	defer m.mu.Unlock()
	fmt.Fprintln(w, "# HELP lens_requests_total Requests by kind (search, image, similar, ask, add) and cache result (exact, semantic, miss).")
	fmt.Fprintln(w, "# TYPE lens_requests_total counter")
	reqs := make([][2]string, 0, len(m.requests))
	for k := range m.requests {
		reqs = append(reqs, k)
	}
	sort.Slice(reqs, func(i, j int) bool { return reqs[i][0]+reqs[i][1] < reqs[j][0]+reqs[j][1] })
	for _, k := range reqs {
		fmt.Fprintf(w, "lens_requests_total{kind=%q,cache=%q} %g\n", k[0], k[1], m.requests[k])
	}
	fmt.Fprintln(w, "# HELP lens_errors_total Failures, by stage.")
	fmt.Fprintln(w, "# TYPE lens_errors_total counter")
	for _, k := range keys(m.errors) {
		fmt.Fprintf(w, "lens_errors_total{stage=%q} %g\n", k, m.errors[k])
	}
	fmt.Fprintln(w, "# HELP lens_llm_tokens_total Tokens sent to and generated by the gateway's models.")
	fmt.Fprintln(w, "# TYPE lens_llm_tokens_total counter")
	for _, k := range keys(m.tokens) {
		fmt.Fprintf(w, "lens_llm_tokens_total{kind=%q} %g\n", k, m.tokens[k])
	}
	fmt.Fprintln(w, "# HELP lens_stage_duration_seconds Time per stage (resize, describe, embed, cache, retrieve, generate, store, total).")
	fmt.Fprintln(w, "# TYPE lens_stage_duration_seconds histogram")
	for _, k := range keys(m.seconds) {
		for _, b := range latencyBuckets {
			fmt.Fprintf(w, "lens_stage_duration_seconds_bucket{stage=%q,le=\"%g\"} %g\n", k, b, m.buckets[k][b])
		}
		fmt.Fprintf(w, "lens_stage_duration_seconds_bucket{stage=%q,le=\"+Inf\"} %g\n", k, m.seconds[k][1])
		fmt.Fprintf(w, "lens_stage_duration_seconds_sum{stage=%q} %g\n", k, m.seconds[k][0])
		fmt.Fprintf(w, "lens_stage_duration_seconds_count{stage=%q} %g\n", k, m.seconds[k][1])
	}
}

func keys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
